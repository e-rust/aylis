//! A lista de classes do aylis-build (usada para gerar o registro enxuto) tem de bater
//! com o que o `register_all` registra, e cada `aylis::classes::X` registra a classe X.

use aylis::core::Ui;

type Register = fn(&mut Ui);

#[test]
fn class_list_matches_register_all() {
    let mut ui = Ui::new();
    aylis::register_all(&mut ui);
    let mut registered: Vec<&str> = ui.registry().iter().map(|c| c.name).collect();
    registered.sort_unstable();
    let mut listed: Vec<&str> = aylis_build::CLASSES.iter().map(|(n, _)| *n).collect();
    listed.sort_unstable();
    assert_eq!(registered, listed, "acrescente a classe nova em aylis_build::CLASSES e em aylis::classes");
}

